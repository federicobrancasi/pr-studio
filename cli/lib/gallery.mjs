// The README gallery. Full videos live in the GitHub release "gallery" (outside git, so clones stay small for people
// and agents); the repo keeps an animated preview and the contact sheet of each video.
//   prs gallery [--upload]   make missing previews, (upload videos to the release), rebuild the README section
import fs from 'node:fs';
import path from 'node:path';
import { execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
import { ROOT, buildDir, findFfmpeg, loadConfig, readJson } from './common.mjs';
import { readHistory } from './history.mjs';
import { loadCatalog } from './catalog.mjs';

const run = promisify(execFile);
const RELEASE = 'gallery';
const START = '<!-- gallery:start (generated by prs gallery) -->';
const END = '<!-- gallery:end -->';

/** One short moment per beat, where its diagram moves the most, then the end card. */
export function previewSegments(project) {
	const out = project.beats.map((b, k) => {
		const len = k === 0 ? 3.0 : 2.4;
		const cues = Object.values(b.cues ?? {}).sort((x, y) => x - y);
		const at = k === 0
			? (b.cues?.stats ?? b.start + 0.4 * (b.end - b.start)) - 0.6
			: (cues.length ? cues[Math.floor(cues.length / 2)] : b.start + 0.45 * (b.end - b.start)) - 0.3;
		const lo = k === 0 ? 0 : b.start + 0.6;
		return [Math.max(lo, Math.min(at, b.end - 0.2 - len)), len];
	});
	out.push([project.video.endAt + 0.4, 1.8]);
	return out;
}

/** An animated WebP trailer (plays inline on GitHub), from the final mp4. */
export async function makePreview(slug, { mp4, out, width = 720, fps = 12 } = {}) {
	const project = readJson(path.join(buildDir(slug), 'project.json'));
	const segs = previewSegments(project);
	const inputs = segs.flatMap(([a, d]) => ['-ss', a.toFixed(2), '-t', d.toFixed(2), '-i', mp4]);
	const chains = segs.map((_, i) => `[${i}:v]fps=${fps},scale=${width}:-2:flags=lanczos:in_color_matrix=bt709:in_range=tv,format=bgra,setsar=1[v${i}]`);
	const filter = `${chains.join(';')};${segs.map((_, i) => `[v${i}]`).join('')}concat=n=${segs.length}:v=1:a=0[out]`;
	fs.mkdirSync(path.dirname(out), { recursive: true });
	await run(findFfmpeg(), ['-v', 'error', '-y', ...inputs, '-filter_complex', filter, '-map', '[out]', '-an', '-c:v', 'libwebp_anim', '-lossless', '0', '-quality', '60', '-compression_level', '6', '-loop', '0', out], { maxBuffer: 16 * 1024 * 1024 });
	return out;
}

function repoOf() {
	const url = execFileSync('git', ['-C', ROOT, 'remote', 'get-url', 'origin'], { encoding: 'utf8' }).trim();
	const m = url.match(/github\.com[:/]([\w.-]+)\/([\w.-]+?)(?:\.git)?$/);
	if (!m) {
		throw new Error(`origin is not a GitHub repository: ${url}`);
	}
	return `${m[1]}/${m[2]}`;
}

function mp4Of(slug) {
	for (const p of [path.join(buildDir(slug), `${slug}.mp4`), path.join(loadConfig().deliver, slug, `${slug}.mp4`)]) {
		if (fs.existsSync(p)) {
			return p;
		}
	}
	return null;
}

const mmss = s => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

async function upload(repo, files) {
	const gh = (...args) => execFileSync('gh', [...args, '--repo', repo], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
	try {
		gh('release', 'view', RELEASE);
	} catch {
		gh('release', 'create', RELEASE, '--title', 'Gallery', '--notes', 'Full videos of the README gallery, made with pr-studio. The repository keeps only previews and contact sheets.', '--target', 'main');
	}
	const existing = new Set(JSON.parse(gh('release', 'view', RELEASE, '--json', 'assets')).assets.map(a => `${a.name}:${a.size}`));
	const todo = files.filter(f => !existing.has(`${path.basename(f)}:${fs.statSync(f).size}`));
	if (todo.length) {
		gh('release', 'upload', RELEASE, ...todo, '--clobber');
	}
	return todo.length;
}

export async function gallery({ upload: doUpload = false } = {}) {
	const repo = repoOf();
	// Only videos published here (with a contact sheet); history also lists the ones cloud sessions made for Slack.
	const entries = readHistory().slice().reverse().filter(e => fs.existsSync(path.join(ROOT, 'gallery', e.slug, 'contact.png')));
	const names = new Map((await loadCatalog()).map(t => [t.id, t.name]));
	const assets = [];
	for (const e of entries) {
		const gdir = path.join(ROOT, 'gallery', e.slug);
		const mp4 = mp4Of(e.slug);
		const preview = path.join(gdir, 'preview.webp');
		if (!fs.existsSync(preview) && mp4 && fs.existsSync(path.join(buildDir(e.slug), 'project.json'))) {
			await makePreview(e.slug, { mp4, out: preview });
			console.log(`preview: ${path.relative(ROOT, preview)} (${(fs.statSync(preview).size / 1e6).toFixed(2)} MB)`);
		}
		if (mp4) {
			assets.push(mp4);
			const srt = mp4.replace(/\.mp4$/, '.srt');
			if (fs.existsSync(srt)) {
				assets.push(srt);
			}
			e.mb = +(fs.statSync(mp4).size / 1e6).toFixed(1);
		}
	}
	if (doUpload) {
		const n = await upload(repo, assets);
		console.log(`release "${RELEASE}": ${n} file${n === 1 ? '' : 's'} uploaded, ${assets.length - n} already there`);
	}
	const base = `https://github.com/${repo}/releases/download/${RELEASE}`;
	const rows = entries.map(e => {
		const video = `${base}/${e.slug}.mp4`;
		const preview = `gallery/${e.slug}/preview.webp`;
		const hasPreview = fs.existsSync(path.join(ROOT, preview));
		const middle = Object.values(e.treatments).slice(1).map(t => names.get(t) ?? t);
		const headline = e.headline ?? e.title;
		return [
			'<tr>',
			'<td width="55%" valign="top">',
			'',
			hasPreview ? `<a href="${video}"><img src="${preview}" alt="${esc(headline)}: preview of the video"></a>` : `<a href="${video}"><img src="gallery/${e.slug}/contact.png" alt="${esc(headline)}: frames"></a>`,
			'',
			'</td>',
			'<td valign="top">',
			'',
			`**${esc(headline)}**<br>`,
			`[${e.repo}#${e.number}](https://github.com/${e.repo}/pull/${e.number}) \u00b7 ${mmss(e.seconds)} \u00b7 ${e.motion === 'canvas' ? 'camera over a board' : 'slides'}`,
			'',
			`<sub>${middle.map(esc).join(' \u2192 ')}</sub>`,
			'',
			`**[\u25b6 Watch the video](${video})**${e.mb ? ` <sub>(${e.mb} MB)</sub>` : ''}<br>`,
			`<sub>[captions](${base}/${e.slug}.srt) \u00b7 [frames](gallery/${e.slug}/contact.png)</sub>`,
			'',
			'</td>',
			'</tr>',
			'<tr>',
			'<td colspan="2">',
			'<details>',
			`<summary>Every beat, frame by frame</summary>`,
			'',
			`<img src="gallery/${e.slug}/contact.png" alt="${esc(headline)}: key frames">`,
			'',
			'</details>',
			'</td>',
			'</tr>',
		].join('\n');
	});
	const block = [START, '<table>', ...rows, '</table>', END].join('\n');
	const readme = path.join(ROOT, 'README.md');
	const text = fs.readFileSync(readme, 'utf8');
	const i = text.indexOf(START), j = text.indexOf(END);
	if (i < 0 || j < 0) {
		throw new Error(`README.md needs the markers ${START} and ${END} where the gallery goes`);
	}
	fs.writeFileSync(readme, text.slice(0, i) + block + text.slice(j + END.length));
	console.log(`README gallery: ${entries.length} videos`);
}
